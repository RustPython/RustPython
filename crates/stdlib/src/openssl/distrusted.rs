pub(super) fn verify(preverified: bool, context: &mut X509StoreContextRef) -> bool {
    if !preverified {
        return false;
    }
    let Some(cert) = context.current_cert() else {
        return true;
    };
    let result = subject_public_key_info(cert).and_then(|spki| {
        openssl::hash::hash(openssl::hash::MessageDigest::sha256(), &spki)
            .ok()
            .filter(|digest| digest.len() == 32)
    });
    let error = match result {
        Some(digest)
            if DISTRUSTED_SPKIS
                .iter()
                .any(|key| key.as_slice() == digest.as_ref()) =>
        {
            openssl_sys::X509_V_ERR_CERT_REJECTED
        }
        Some(_) => return true,
        None => openssl_sys::X509_V_ERR_UNSPECIFIED,
    };
    // Both values are public X509 verification result constants.
    context.set_error(unsafe { X509VerifyResult::from_raw(error) });
    false
}

// Preserve the certificate's exact SPKI encoding. Re-encoding an EVP_PKEY can
// normalize its algorithm parameters and therefore change the fingerprint.
fn subject_public_key_info(cert: &openssl::x509::X509Ref) -> Option<Vec<u8>> {
    unsafe {
        let spki = X509_get_X509_PUBKEY(cert.as_ptr());
        if spki.is_null() {
            return None;
        }
        let length = i2d_X509_PUBKEY(spki, core::ptr::null_mut());
        if length <= 0 {
            return None;
        }
        let mut encoded = vec![0; length as usize];
        let mut output = encoded.as_mut_ptr();
        let written = i2d_X509_PUBKEY(spki, &mut output);
        (written == length).then_some(encoded)
    }
}

