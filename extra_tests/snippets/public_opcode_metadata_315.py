EXPECTED_STACK_SHA256 = (
    "37dc8fdfed5c2a15665eece22718422b02721a1d9ce6e4963b89c04727074f37"
)

actual_flags = tuple(
    sum(int(getattr(_opcode, name)(op)) << bit for bit, name in enumerate(FLAGS))
    for op in range(-1, 513)
)
assert len(actual_flags) == 514
assert actual_flags == EXPECTED_FLAGS
assert _opcode.is_valid(255) and _opcode.has_arg(255)
assert all(not _opcode.is_valid(op) for op in (219, 220, 221))
rows = []
for op in range(-1, 513):
    for arg in (0, 1, 2, 3, 4, 8, 255):
        for jump in (None, False, True):
            try:
                value = _opcode.stack_effect(op, arg, jump=jump)
            except Exception as exc:
                value = [type(exc).__name__, str(exc)]
            rows.append([op, arg, jump, value])
assert len(rows) == 10794
assert (
    hashlib.sha256(json.dumps(rows, separators=(",", ":")).encode()).hexdigest()
    == EXPECTED_STACK_SHA256
)
assert all(
    _opcode.stack_effect(255, arg, jump=jump) == 0
    for arg in (0, 255)
    for jump in (None, False, True)
)
