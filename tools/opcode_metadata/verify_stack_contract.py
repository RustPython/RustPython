"""Regenerate independent C stack goldens, or fail if checked-in rows differ."""

import argparse
import subprocess
import tempfile
from pathlib import Path

from target_source import verify_source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    verify_source(args.source)
    here = Path(__file__).resolve().parent
    with tempfile.TemporaryDirectory() as temporary:
        binary = Path(temporary) / "stack-contract"
        subprocess.run(
            [
                "cc",
                "-I" + str(args.build),
                "-I" + str(args.source / "Include"),
                "-I" + str(args.source / "Include/internal"),
                str(here / "stack_contract.c"),
                "-o",
                str(binary),
            ],
            check=True,
        )
        output = subprocess.check_output([str(binary)], text=True)
    rows = [tuple(map(int, line.split())) for line in output.splitlines()]
    assert len(rows) == 3430 and len(set(rows)) == 3430
    contents = (
        "// Generated by tools/opcode_metadata/verify_stack_contract.py from pinned CPython C metadata.\n"
        "const TARGET_STACK_CASES: &[(u16, u32, u32, u32)] = &[\n"
        + "".join(f"    ({op}, {arg}, {pop}, {push}),\n" for op, arg, pop, push in rows)
        + "];\n"
    )
    target = here.parents[1] / "crates/compiler-core/src/bytecode/target_stack_cases.rs"
    if args.write:
        target.write_text(contents)
    elif target.read_text() != contents:
        raise SystemExit("pinned C stack rows differ")
    print(f"Verified {len(rows)} exact C stack rows")


if __name__ == "__main__":
    main()
